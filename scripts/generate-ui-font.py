#!/usr/bin/env python3
"""Bake Inter glyphs into src/ui/ui_font_data.h as 4-bit alpha bitmaps.

The PS3 build has no font rasterizer, so the UI ships pre-rendered glyphs for
printable ASCII and Latin-1 (enough for most song titles). Inter is licensed
under the SIL Open Font License 1.1; see licenses/INTER-OFL-1.1.txt.

Usage: generate-ui-font.py [INTER_DIR] [OUTPUT]
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

INTER_DIR = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter")
OUTPUT = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src/ui/ui_font_data.h")

# name, file, pixel size
FACES = [
    ("small", "Inter-SemiBold.otf", 19),
    ("body", "Inter-Medium.otf", 30),
    ("title", "InterDisplay-SemiBold.otf", 56),
]
CODEPOINTS = list(range(32, 127)) + list(range(160, 256))


def render_face(path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        advance = font.getlength(ch)
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(data)
        if w and h and not ch.isspace():
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            px = img.tobytes()
            nibbles = [(v * 15 + 127) // 255 for v in px]
            if len(nibbles) % 2:
                nibbles.append(0)
            for i in range(0, len(nibbles), 2):
                data.append((nibbles[i] << 4) | nibbles[i + 1])
        else:
            w = h = 0
        glyphs.append((int(round(advance * 4)), left, top, w, h, offset))
    return ascent, descent, glyphs, bytes(data)


def main():
    out = [
        "/* Generated by scripts/generate-ui-font.py. Do not edit.",
        " * Glyphs rasterized from Inter (SIL OFL 1.1, licenses/INTER-OFL-1.1.txt). */",
        "#ifndef PS3_AIRPLAY_UI_FONT_DATA_H",
        "#define PS3_AIRPLAY_UI_FONT_DATA_H",
        "",
        '#include "ui_font.h"',
        "",
    ]
    for name, filename, size in FACES:
        ascent, descent, glyphs, data = render_face(INTER_DIR / filename, size)
        out.append(f"static const uint8_t ui_font_{name}_alpha[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            out.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
        if not data:
            out.append("\t0")
        out.append("};")
        out.append(f"static const ui_glyph ui_font_{name}_glyphs[{len(glyphs)}] = {{")
        for adv, x, y, w, h, off in glyphs:
            out.append(f"\t{{{adv},{x},{y},{w},{h},{off}}},")
        out.append("};")
        out.append(
            f"static const ui_font ui_font_{name} = {{ {size}, {ascent}, {descent}, "
            f"{len(glyphs)}, ui_font_{name}_glyphs, ui_font_{name}_alpha }};"
        )
        out.append("")
        print(f"{name}: {size}px, {len(data)} bytes of glyph data", file=sys.stderr)
    out.append("#endif")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
